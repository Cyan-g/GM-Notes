// The only bridge between the pages and the computer: a few named calls, nothing else.
const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('dndesk', {
  read: (root, rel) => ipcRenderer.invoke('fs:read', root, rel),
  write: (root, rel, bytes) => ipcRenderer.invoke('fs:write', root, rel, bytes),
  list: (root, rel) => ipcRenderer.invoke('fs:list', root, rel),
  remove: (root, rel) => ipcRenderer.invoke('fs:remove', root, rel),
  getFolder: root => ipcRenderer.invoke('folder:get', root),
  pickFolder: root => ipcRenderer.invoke('folder:pick', root),
  showFolder: root => ipcRenderer.invoke('app:show-folder', root),
  info: () => ipcRenderer.invoke('app:info'),
  open: url => ipcRenderer.invoke('app:open', url),
  cardsPdf: (pageSize, name) => ipcRenderer.invoke('cards:pdf', pageSize, name),
  db: {
    load: (types, kinds) => ipcRenderer.invoke('db:load', types, kinds),
    create: (d, types, kinds) => ipcRenderer.invoke('db:create', d, types, kinds),
    save: changes => ipcRenderer.invoke('db:save', changes),
    history: id => ipcRenderer.invoke('db:history', id),
    deleted: () => ipcRenderer.invoke('db:deleted'),
    copyTo: (root, rel) => ipcRenderer.invoke('db:copy-to', root, rel),
    restore: name => ipcRenderer.invoke('db:restore', name),
  },
  publish: {
    folder: () => ipcRenderer.invoke('publish:folder'),
    pick: () => ipcRenderer.invoke('publish:pick'),
  },
  shared: {
    scan: () => ipcRenderer.invoke('shared:scan'),
    follow: (folder, worldId, live) => ipcRenderer.invoke('shared:follow', folder, worldId, live),
    get: () => ipcRenderer.invoke('shared:get'),
  },
  worlds: {
    list: () => ipcRenderer.invoke('worlds:list'),
    switch: dir => ipcRenderer.invoke('worlds:switch', dir),
    forget: dir => ipcRenderer.invoke('worlds:forget', dir),
    create: name => ipcRenderer.invoke('worlds:create', name),
    newId: title => ipcRenderer.invoke('worlds:new-id', title),
    moved: title => ipcRenderer.invoke('worlds:moved', title),
    move: dir => ipcRenderer.invoke('worlds:move', dir),
  },
  live: {
    hostStatus: () => ipcRenderer.invoke('live:host-status'),
    start: title => ipcRenderer.invoke('live:host-start', title),
    stop: () => ipcRenderer.invoke('live:host-stop'),
    newCode: () => ipcRenderer.invoke('live:new-code'),
    sent: () => ipcRenderer.invoke('live:sent'),
    discover: () => ipcRenderer.invoke('live:discover'),
    check: (target, code) => ipcRenderer.invoke('live:check', target, code),
    follow: who => ipcRenderer.invoke('live:follow', who),
    playerStatus: () => ipcRenderer.invoke('live:player-status'),
    onHost: cb => ipcRenderer.on('live:host', (_e, s) => cb(s)),
    onPlayer: cb => ipcRenderer.on('live:player', (_e, s) => cb(s)),
    onPublished: cb => ipcRenderer.on('live:published', (_e, p) => cb(p)),
    sendCharacters: text => ipcRenderer.invoke('live:send-characters', text),
    onCharacter: cb => ipcRenderer.on('live:character', (_e, msg) => cb(msg)),
  },
  onUpdate: cb => ipcRenderer.on('update', (_e, info) => cb(info)),
  installUpdate: () => ipcRenderer.invoke('update:install'),
})
